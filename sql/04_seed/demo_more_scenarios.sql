INSERT INTO CORE.ORDER_LINE (ORDER_LINE_ID, ORDER_ID, LINE_NUMBER, PART_ID, REQUIRED_QUANTITY, UNIT)
SELECT COLUMN1, COLUMN2, 1, COLUMN3, COLUMN4, 'PCS'
FROM VALUES
    ('ORD_002_LINE_001', 'ORD_002', 'PART_MOTOR_001',      200),
    ('ORD_003_LINE_001', 'ORD_003', 'PART_CONTROLLER_001', 50),
    ('ORD_004_LINE_001', 'ORD_004', 'PART_FAN_001',        100);

