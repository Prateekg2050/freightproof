    ('CLAIM_ERP_MOT_001', 'REC_ERP_MOT_001', 'SYS_ERP', 'PART_MOTOR_001',      300, 2),
    ('CLAIM_WMS_MOT_001', 'REC_WMS_MOT_001', 'SYS_WMS', 'PART_MOTOR_001',      298, 1),
    ('CLAIM_ERP_CTL_001', 'REC_ERP_CTL_001', 'SYS_ERP', 'PART_CONTROLLER_001', 80,  2),
    ('CLAIM_ERP_FAN_001', 'REC_ERP_FAN_001', 'SYS_ERP', 'PART_FAN_001',        400, 180),
    ('CLAIM_WMS_FAN_001', 'REC_WMS_FAN_001', 'SYS_WMS', 'PART_FAN_001',        400, 180);

-- Orders: one per scenario
INSERT INTO CORE.CUSTOMER_ORDER (ORDER_ID, EXTERNAL_ORDER_ID, PLANT_ID, PRIORITY, REQUIRED_BY, ORDER_VALUE)
