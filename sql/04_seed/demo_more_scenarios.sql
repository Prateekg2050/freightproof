    SOURCE_RECORD_ID, SOURCE_SYSTEM_ID, EXTERNAL_RECORD_ID, RECORD_TYPE,
    RECORD_VERSION, PAYLOAD, SOURCE_UPDATED_AT, INGESTION_STATUS
)
