       OBJECT_CONSTRUCT('part', COLUMN4, 'quantity', COLUMN5, 'unit', 'PCS', 'quantity_type', 'USABLE'),
       DATEADD('MINUTE', -COLUMN6, CURRENT_TIMESTAMP()), 'VALIDATED'
FROM VALUES
    ('REC_ERP_MOT_001',  'SYS_ERP', 'ERP-INV-6001',   'ERP-MOT-01',  300, 2),
    ('REC_WMS_MOT_001',  'SYS_WMS', 'WMS-STOCK-9001', 'WH-MOTOR-A',  298, 1),
    ('REC_ERP_CTL_001',  'SYS_ERP', 'ERP-INV-6002',   'ERP-CTL-01',  80,  2),
    ('REC_ERP_FAN_001',  'SYS_ERP', 'ERP-INV-6003',   'ERP-FAN-01',  400, 180),
    ('REC_WMS_FAN_001',  'SYS_WMS', 'WMS-STOCK-9003', 'WH-FAN-A',    400, 180);

-- Inventory claims
